local function ValidateKeyFromFile()
    local key, storedDevice = GetBoundKey()
    if not key or not storedDevice then
        return false, "No key file found. Please enter key."
    end

    local currentDevice = GetDeviceID()
    if storedDevice ~= currentDevice then
        return false, "Key is bound to another device!\nPlease re-enter your key."
    end

    local keyData = EMBEDDED_KEYS[key]
    if not keyData then return false, "Invalid key! (not registered)" end
    if not keyData.active then return false, "Key has been banned!" end

    local devices, limit = GetKeyDevices(keyData)
    if #devices > 0 and not DeviceInList(devices, currentDevice) then
        if #devices >= limit then
            return false, "Device limit reached (" .. #devices .. "/" .. limit .. ")."
        end
    end

    if not CheckExpiry(keyData.expiry) then
        return false, "Key expired! " .. keyData.expiry
    end

    _G.VALID_KEY_TYPE = "VIP"
    _G.USER_EXPIRY_TIME = keyData.expiry
    return true, "Valid"
end

