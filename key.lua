-- ==================== 3. HELPERS ====================
local function GetDeviceID()
    local deviceID = ""
    pcall(function()
        local SystemUtil = import("SystemUtil")
        if SystemUtil and SystemUtil.GetAndroidID then
            deviceID = SystemUtil:GetAndroidID() or ""
        end
    end)
    if deviceID == "" or deviceID == "nil" then
        pcall(function()
            local settings = import("GameUserSettings")
            if settings and settings.GetUniqueNetId then
                deviceID = tostring(settings:GetUniqueNetId() or "")
            end
        end)
    end
    if deviceID == "" or deviceID == "nil" then
        pcall(function()
            local f = io.open(DEVICE_ID_CACHE, "r")
            if f then
                deviceID = f:read("*all"):gsub("%s+", "")
                f:close()
            end
            if deviceID == "" or deviceID == "nil" then
                local seed = os.time() + math.random(1000, 9999)
                deviceID = "GEN_" .. tostring(seed):gsub("%-", "")
                local wf = io.open(DEVICE_ID_CACHE, "w")
                if wf then wf:write(deviceID); wf:close() end
            end
        end)
    end
    return deviceID or "UNKNOWN_DEVICE"
end

local function SaveBoundKey(key, deviceID)
    local f = io.open(EREN_KEY_FILE, "w")
    if f then f:write(key .. "|" .. deviceID); f:close(); return true end
    return false
end

local function GetBoundKey()
    local f = io.open(EREN_KEY_FILE, "r")
    if not f then return nil, nil end
    local content = f:read("*all"):gsub("%s+", "")
    f:close()
    if content == "" then return nil, nil end
    local key, device = content:match("([^|]+)|(.+)")
    if key and device then return key, device end
    return content, nil
end

local function GetKeyDevices(keyData)
    local list = {}
    if type(keyData.devices) == "table" then
        for _, d in ipairs(keyData.devices) do
            if type(d) == "string" and d ~= "" then table.insert(list, d) end
        end
    elseif type(keyData.device) == "string" and keyData.device ~= "" then
        table.insert(list, keyData.device)
    end
    return list, tonumber(keyData.max_devices) or 1
end

local function DeviceInList(devices, id)
    for _, d in ipairs(devices) do
        if d == id then return true end
    end
    return false
end

local function CheckExpiry(expiry)
    if not expiry or expiry == "" then return true end
    local y = tonumber(expiry:sub(1,4))
    local m = tonumber(expiry:sub(6,7))
    local d = tonumber(expiry:sub(9,10))
    if not (y and m and d) then return true end
    return os.time() <= os.time({year=y, month=m, day=d, hour=23, min=59, sec=0})
end

