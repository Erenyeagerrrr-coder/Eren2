function REGER_KEYBOARD:CheckUnlock()
    local input = self._inputText or ""
    if input == "" then self:ShowUnlockMessage("❌ Please enter a key!"); return end

    local keyData = EMBEDDED_KEYS[input]
    if not keyData then
        self:ShowUnlockMessage("❌ Invalid Key!")
        self:ClearInput()
        return
    end
    if not keyData.active then
        self:ShowUnlockMessage("❌ Key is Banned!")
        self:ClearInput()
        return
    end
    if not CheckExpiry(keyData.expiry) then
        self:ShowUnlockMessage("❌ Key Expired! " .. keyData.expiry)
        self:ClearInput()
        return
    end

    local currentDevice = GetDeviceID()
    local devices, limit = GetKeyDevices(keyData)

    if #devices > 0 and not DeviceInList(devices, currentDevice) then
        if #devices >= limit then
            self:ShowUnlockMessage("❌ Device limit reached (" .. #devices .. "/" .. limit .. ")!")
            self:ClearInput()
            return
        end
    end

    SaveBoundKey(input, currentDevice)

    self._isUnlocked = true
    _G.VALID_KEY_TYPE = "VIP"
    _G.USER_EXPIRY_TIME = keyData.expiry
    _G.ACTIVE_LICENSE_KEY = input

    self:ShowUnlockMessage("✅ Key Activated & Bound Successfully!")
    self:CloseKeyboard()

    local usedSlots = #devices
    if not DeviceInList(devices, currentDevice) then usedSlots = usedSlots + 1 end

    pcall(function()
        local Msg = require("client.slua.logic.common.logic_common_msg_box")
        if Msg and Msg.Show then
            Msg.Show(4, "ACCESS GRANTED",
                "VIP Key Verified!\nDevice Bound: " .. currentDevice ..
                "\nSlots: " .. usedSlots .. "/" .. limit ..
                "\nExpiry: " .. (keyData.expiry ~= "" and keyData.expiry or "Lifetime"),
                function() end)
        end
    end)
end

function REGER_KEYBOARD:ToggleKeyboard()
    if self._isOpen then self:CloseKeyboard() else self:OpenKeyboard() end
end

function REGER_KEYBOARD:OpenKeyboard()
    if self._isOpen then return end
    self._isOpen = true
    self:ClearInput()
    self:CreateKeyboardWidget()
    if self._keyboardWidget and IsValid(self._keyboardWidget) then
        self._keyboardWidget:SetWidgetVisibility(UEnums.ESlateVisibility.SelfHitTestInvisible)
    end
end

function REGER_KEYBOARD:CloseKeyboard()
    self._isOpen = false
    for _, btn in pairs(self._buttons) do
        if IsValid(btn) then
            pcall(function()
                btn:SetWidgetVisibility(UEnums.ESlateVisibility.Collapsed)
                btn:RemoveFromParent()
            end)
        end
    end
    self._buttons = {}
    if self._keyboardWidget and IsValid(self._keyboardWidget) then
        pcall(function()
            self._keyboardWidget:SetWidgetVisibility(UEnums.ESlateVisibility.Collapsed)
            self._keyboardWidget:RemoveFromParent()
            self._keyboardWidget:ConditionalBeginDestroy()
        end)
        self._keyboardWidget = nil
    end
    self._inputText = ""
    if self._displayText and IsValid(self._displayText) then self._displayText:SetText("") end
end

function REGER_KEYBOARD:Start()
    pcall(function()
        self:CreateTriggerButton()
        print("[REGER KEYBOARD] Started")
    end)
end

